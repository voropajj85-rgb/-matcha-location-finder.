// Package the existing pure backend policy for the static frontend. No policy edits.
// No bundler dependency, eval, network, database code or discovery execution.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../scripts/ingest');
const output = path.resolve(__dirname, '../js/generated/market-policy.js');
const modules = new Map();
function collect(name) {
  if (modules.has(name)) return;
  if (name === 'crypto') {
    // Discovery ID generation is unreachable from the policy exports. Fail closed if called.
    modules.set(name, 'module.exports = { createHash() { throw new Error("Discovery hashing is unavailable in the UI"); } };');
    return;
  }
  if (!/^[a-z-]+$/.test(name)) throw new Error(`Unexpected policy dependency: ${name}`);
  const source = fs.readFileSync(path.join(root, `${name}.js`), 'utf8').replace(/\r\n/g, '\n');
  modules.set(name, source);
  for (const [, dependency] of source.matchAll(/require\(['"]([^'"]+)['"]\)/g)) collect(dependency.replace(/^\.\//, ''));
}
['market-funnel', 'district-coverage', 'listing-validation', 'project-relevance'].forEach(collect);
const code = '// GENERATED by node scripts/build-ui-policy.js — do not edit. Backend policy is copied unchanged.\n'
  + 'const factories = {\n' + [...modules].map(([name, source]) => `${JSON.stringify(name)}: function(module, exports, require) {\n${source}\n}`).join(',\n')
  + '\n};\nconst cache = {};\nfunction load(name) {\n name = name.replace(/^\\.\\//, "");\n if (!cache[name]) { const module = cache[name] = { exports: {} }; factories[name](module, module.exports, load); }\n return cache[name].exports;\n}\n'
  + 'export const { classifyMarketListing } = load("market-funnel");\nexport const { districtBucket } = load("district-coverage");\nexport const { getValidExternalUrl } = load("listing-validation");\nexport const { isPriceOnRequest } = load("project-relevance");\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== code) throw new Error('UI policy is stale; run node scripts/build-ui-policy.js');
  console.log('Browser policy matches backend source.');
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, code);
  console.log(`Packaged ${modules.size} pure policy modules.`);
}
